def _slugify(text: str) -> str:
    plain = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", plain.lower().replace("'", "")).strip("-")


def _authors_to_people() -> None:
    """Each book's author line as people, split where it names several ("Betje Wolff & Aagje Deken")."""
    bind = op.get_bind()
    people: dict[str, int] = {}
    used: set[str] = set()
    for book_id, author in bind.execute(sa.text("SELECT id, author FROM books ORDER BY id")).all():
        # an anonymous book has no authors, and the site says "Anonymous"
        names = list(dict.fromkeys(n.strip() for n in re.split(r"\s+(?:and|&)\s+", author) if n.strip()))
        names = [n for n in names if n.lower() not in {"anonymous", "unknown author"}]
        for position, name in enumerate(names):
            person_id = people.get(name.lower())
            if person_id is None:
                base = _slugify(name) or "someone"
                slug, n = base, 1
                while slug in used:
                    n += 1
                    slug = f"{base}-{n}"
                used.add(slug)
                person_id = bind.execute(
                    sa.text("INSERT INTO people (slug, name) VALUES (:slug, :name) RETURNING id"), {"slug": slug, "name": name}
                ).scalar_one()
                people[name.lower()] = person_id
            bind.execute(
                sa.text("INSERT INTO book_authors (book_id, person_id, position) VALUES (:b, :p, :i)"),
                {"b": book_id, "p": person_id, "i": position},
            )


